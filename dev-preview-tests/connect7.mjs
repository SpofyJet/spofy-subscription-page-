import { chromium, devices } from 'playwright'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' })
let pass = 0, fail = 0
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); c ? pass++ : fail++ }
const ctx = await browser.newContext({ ...devices['iPhone 13'], colorScheme: 'dark', locale: 'ru-RU' })
const page = await ctx.newPage()
await page.goto('http://localhost:3334/nodevices/demo7Kx2pQ9mZ4aB', { waitUntil: 'networkidle' }); await page.waitForTimeout(1200)
const cta = page.getByRole('button', { name: 'Подключить устройство' })
const where = () => page.locator('#sp-connect').evaluate((el) => Math.round(el.getBoundingClientRect().top))
await cta.tap()
const flashed = await page.locator('#sp-connect[data-flash]').count()
await page.waitForTimeout(1100)
let top = await where()
ok(top >= 0 && top <= 30, `tap → guide at the top of the screen (y=${top})`)
ok(flashed === 1, 'tap → the guide flashes')
// tap right after closing a purchase window
await page.evaluate(() => window.scrollTo(0, 0)); await page.waitForTimeout(300)
await page.getByRole('button', { name: /QR-код для другого устройства/ }).tap(); await page.waitForTimeout(800)
await page.keyboard.press('Escape')
await cta.tap()
await page.waitForTimeout(1400)
top = await where()
ok(top >= 0 && top <= 30, `tap just after closing a window → guide at the top (y=${top})`)
// already on screen: still answers (flash)
await cta.scrollIntoViewIfNeeded()
await cta.tap()
ok((await page.locator('#sp-connect[data-flash]').count()) === 1, 'tap when the guide is already visible → it flashes')
// reselecting the chosen system goes to the steps
await page.evaluate(() => window.scrollTo(0, 0)); await page.waitForTimeout(200)
await page.getByRole('radio', { checked: true }).first().tap(); await page.waitForTimeout(1100)
const stepsTop = await page.locator('#sp-connect ol').evaluate((el) => Math.round(el.getBoundingClientRect().top))
ok(stepsTop >= 0 && stepsTop < 200, `chosen system tapped again → steps in view (y=${stepsTop})`)
console.log(`${pass} PASS, ${fail} FAIL`)
await browser.close()
