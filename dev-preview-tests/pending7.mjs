import { chromium, devices } from 'playwright'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' })
let pass = 0, fail = 0
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); c ? pass++ : fail++ }
const ctx = await browser.newContext({ ...devices['iPhone 13'], colorScheme: 'dark', locale: 'ru-RU' })
const page = await ctx.newPage()
await page.goto('http://localhost:3334/active/demo7Kx2pQ9mZ4aB', { waitUntil: 'networkidle' }); await page.waitForTimeout(1200)
const dlg = page.getByRole('dialog')
await page.locator('ul li').getByRole('button', { name: /Продлить/ }).click(); await page.waitForTimeout(700)
await dlg.getByRole('button', { name: /Продолжить/ }).click(); await page.waitForTimeout(300)
const pop = ctx.waitForEvent('page'); await dlg.getByRole('button', { name: /Оплатить/ }).click(); const tab = await pop; await page.waitForTimeout(600); await tab.close()
ok(/Счёт создан/.test(await dlg.innerText()), 'new invoice is shown right after «Оплатить»')
await page.keyboard.press('Escape'); await page.waitForTimeout(500)
ok(await page.getByText(/Ждём оплату 720/).isVisible(), 'banner «Ждём оплату 720 ₽» on the page')
await page.locator('ul li').getByRole('button', { name: /Добавить/ }).click(); await page.waitForTimeout(800)
let txt = (await dlg.innerText()).replace(/\s+/g, ' ')
ok(/Устройства/.test(txt) && /Сколько устройств добавить/.test(txt), '«Добавить» opens the devices choice, not the old invoice')
ok(/Есть неоплаченный счёт: Продление на 3 месяца, 720 ₽/.test(txt) && /прошлый не оплачивайте/.test(txt), 'note about the unpaid invoice on top')
await dlg.getByRole('button', { name: 'Открыть счёт' }).click(); await page.waitForTimeout(500)
ok(/Счёт создан/.test(await dlg.innerText()), '«Открыть счёт» shows the invoice')
await dlg.getByRole('button', { name: /Изменить выбор/ }).click(); await page.waitForTimeout(500)
txt = (await dlg.innerText()).replace(/\s+/g, ' ')
ok(/Есть неоплаченный счёт/.test(txt) && !/Счёт создан — осталось/.test(txt), '«Изменить выбор» goes back to the choice and keeps watching the invoice')
await page.keyboard.press('Escape'); await page.waitForTimeout(400)
await page.getByRole('button', { name: /Ждём оплату|Оплата получена/ }).first().click(); await page.waitForTimeout(500)
ok(/Счёт создан|Оплата получена/.test(await dlg.innerText()), 'banner opens the invoice')
// wait for «paid» (stand: 3rd poll)
await page.waitForFunction(() => /Оплата получена/.test(document.querySelector('[role=dialog]')?.innerText ?? ''), null, { timeout: 30000 }).catch(() => {})
txt = (await dlg.innerText()).replace(/\s+/g, ' ')
ok(/Оплата получена/.test(txt) && (await dlg.getByRole('button', { name: /Изменить выбор/ }).count()) === 0, 'money received: no «Изменить выбор»')
await page.keyboard.press('Escape'); await page.waitForTimeout(300)
await page.locator('ul li').getByRole('button', { name: /Добавить/ }).click(); await page.waitForTimeout(600)
ok(/Оплата получена|Оплачено/.test(await dlg.innerText()), 'money received: buttons show the payment status, not a new purchase')
await page.keyboard.press('Escape')
const nav = page.waitForEvent('load', { timeout: 30000 }).then(() => true).catch(() => false)
await page.waitForFunction(() => /обновляем страницу/.test(document.body.innerText), null, { timeout: 30000 }).catch(() => {})
ok(await page.getByText(/Оплата прошла — обновляем страницу/).isVisible().catch(() => false), 'applied with the window closed: «Оплата прошла — обновляем страницу…»')
ok(await nav, '…and the page reloads by itself')
await page.waitForTimeout(1500)
ok((await page.getByText(/Ждём оплату|обновляем/).count()) === 0, 'after reload: no banner left')
// hide button
await page.locator('ul li').getByRole('button', { name: /Продлить/ }).click(); await page.waitForTimeout(700)
await dlg.getByRole('button', { name: /Продолжить/ }).click(); await page.waitForTimeout(300)
const pop2 = ctx.waitForEvent('page'); await dlg.getByRole('button', { name: /Оплатить/ }).click(); const t2 = await pop2; await page.waitForTimeout(500); await t2.close()
await page.keyboard.press('Escape'); await page.waitForTimeout(400)
await page.getByRole('button', { name: 'Скрыть' }).click(); await page.waitForTimeout(300)
ok((await page.getByText(/Ждём оплату/).count()) === 0, '«Скрыть» removes the banner')
console.log(`${pass} PASS, ${fail} FAIL`)
await browser.close()
